<?php

declare(strict_types=1);

namespace AgentEngine\SymfonyAi\Config;

use Symfony\Component\Config\Definition\Builder\ArrayNodeDefinition;
use Symfony\Component\Config\Definition\Configurator\DefinitionConfigurator;

return static function (DefinitionConfigurator $configurator): void {
    $root = $configurator->rootNode();
    \assert($root instanceof ArrayNodeDefinition);

    $authMethods = static fn (array $auth): int => (int) ($auth['client_id'] !== null && $auth['client_secret'] !== null)
        + (int) ($auth['access_token'] !== null && $auth['access_token_expires_at'] !== null)
        + (int) ($auth['token_provider'] !== null);

    $root
        ->children()
            ->scalarNode('base_url')
                ->defaultValue('https://agentengine.mongodb.com')
                ->cannotBeEmpty()
            ->end()
            ->scalarNode('project_id')
                ->isRequired()
                ->cannotBeEmpty()
            ->end()
            ->scalarNode('contract_version')
                ->defaultNull()
            ->end()
            ->scalarNode('workspace_id')
                ->info('Default workspace for the agent-engine:deploy and agent-engine:invoke commands.')
                ->defaultNull()
            ->end()
            ->scalarNode('transport')
                ->info('Service ID of an AgentEngine\\Http\\Transport implementation.')
                ->defaultNull()
            ->end()
            ->scalarNode('psr18_client')
                ->info('Service ID of a PSR-18 client, wrapped in AgentEngine\\Http\\Psr18Transport.')
                ->defaultNull()
            ->end()
            ->scalarNode('cache')
                ->info('Service ID of a PSR-16 cache for service-account tokens.')
                ->defaultNull()
            ->end()
            ->arrayNode('auth')
                ->isRequired()
                ->children()
                    ->scalarNode('client_id')->defaultNull()->end()
                    ->scalarNode('client_secret')->defaultNull()->end()
                    ->scalarNode('access_token')->defaultNull()->end()
                    ->scalarNode('access_token_expires_at')
                        ->info('An ISO 8601 date-time, required with access_token.')
                        ->defaultNull()
                    ->end()
                    ->scalarNode('token_provider')
                        ->info('Service ID of an AgentEngine\\Auth\\TokenProvider implementation.')
                        ->defaultNull()
                    ->end()
                ->end()
                ->validate()
                    ->ifTrue(static fn (array $auth): bool => 1 !== $authMethods($auth))
                    ->thenInvalid('Configure exactly one authentication method: client_id with client_secret, access_token with access_token_expires_at, or token_provider.')
                ->end()
            ->end()
            ->arrayNode('platform')
                ->children()
                    ->scalarNode('name')
                        ->defaultValue('agent_engine')
                        ->cannotBeEmpty()
                    ->end()
                    ->arrayNode('models')
                        ->info('Maps a Symfony AI model name to an Agent Engine workspace ID.')
                        ->useAttributeAsKey('name')
                        ->normalizeKeys(false)
                        ->scalarPrototype()->cannotBeEmpty()->end()
                        ->defaultValue([])
                    ->end()
                ->end()
                ->validate()
                    ->ifTrue(static fn (array $platform): bool => [] === $platform['models'])
                    ->thenInvalid('Configure at least one entry under "platform.models".')
                ->end()
            ->end()
            ->arrayNode('memory')
                ->children()
                    ->scalarNode('user_id')
                        ->info('Default user whose memories are loaded. Override per invocation with the agent_engine_user_id option.')
                        ->isRequired()
                        ->cannotBeEmpty()
                    ->end()
                    ->scalarNode('session_id')->defaultNull()->end()
                    ->integerNode('max_tokens')->min(1)->defaultNull()->end()
                    ->integerNode('top_k')->min(1)->max(200)->defaultNull()->end()
                    ->arrayNode('enabled_sources')
                        ->scalarPrototype()->cannotBeEmpty()->end()
                        ->defaultValue([])
                    ->end()
                    ->scalarNode('format_style')->defaultNull()->end()
                ->end()
            ->end()
        ->end()
        ->validate()
            ->ifTrue(static fn (array $config): bool => null !== $config['transport'] && null !== $config['psr18_client'])
            ->thenInvalid('Configure either "transport" or "psr18_client", not both.')
        ->end();
};
